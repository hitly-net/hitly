/**
 * Renders every branded HITLy email template with sample (fictional) data
 * and writes committed HTML snapshots to docs/emails/ for review.
 *
 * Run from the repo root: yarn workspace @hitly/mail snapshots
 * The fixtures use no real IDs, hosts or tokens.
 */

import { mkdirSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import path from 'node:path'
import {
  renderAddedToWorkspaceEmail,
  renderDecisionNeededEmail,
  renderEmailChangedNoticeEmail,
  renderEmailChangeVerificationEmail,
  renderInviteEmail,
  renderPasswordChangedEmail,
  renderPasswordResetEmail,
  type RenderedEmail,
} from '../src/index'

const APP_URL = 'https://hitly.net'
const OUT_DIR = fileURLToPath(new URL('../../../docs/emails/', import.meta.url))

const NOW = new Date('2026-11-11T12:00:00Z')

const samples: Record<string, () => Promise<RenderedEmail>> = {
  'decision-needed': () =>
    renderDecisionNeededEmail({
      appUrl: APP_URL,
      approvalId: 'demo-item-1',
      greetingName: 'Alex Reviewer',
      projectName: 'Website relaunch',
      envelope: { prompt: 'Which venue should we book for the launch?' },
      origin: { plugin: 'mcp', agentName: 'Weekend planner' },
      requestedByKey: null,
      expiresAt: '2026-11-11T15:00:00.000Z',
      now: NOW,
    }),
  'invite': () =>
    renderInviteEmail({
      appUrl: APP_URL,
      workspaceName: 'Acme Studio',
      link: `${APP_URL}/invite/demo-invite-token`,
      inviteeEmail: 'new.person@example.com',
      ttlDays: 7,
    }),
  'added-to-workspace': () =>
    renderAddedToWorkspaceEmail({ appUrl: APP_URL, workspaceName: 'Acme Studio' }),
  'password-reset': () =>
    renderPasswordResetEmail({ appUrl: APP_URL, link: `${APP_URL}/reset-password?token=demo-one-time-token` }),
  'email-change-verify': () =>
    renderEmailChangeVerificationEmail({
      appUrl: APP_URL,
      link: `${APP_URL}/verify-email-change?token=demo-one-time-token`,
      ttlHours: 24,
    }),
  'email-changed-notice': () => renderEmailChangedNoticeEmail({ appUrl: APP_URL }),
  'password-changed': () => renderPasswordChangedEmail({ appUrl: APP_URL }),
}

mkdirSync(OUT_DIR, { recursive: true })
for (const [name, build] of Object.entries(samples)) {
  const mail = await build()
  const banner = `<!--\n  Rendered snapshot of the HITLy "${name}" email (generated by\n`
    + `  packages/mail/scripts/render-snapshots.ts — fictional sample data only).\n`
    + `  Subject: ${mail.subject}\n-->\n`
  writeFileSync(path.join(OUT_DIR, `${name}.html`), banner + mail.html, 'utf8')
  console.log(`wrote docs/emails/${name}.html`)
}
